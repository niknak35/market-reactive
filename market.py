from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from functools import lru_cache
from statistics import median
import math
import pandas as pd
import pandas_market_calendars as mcal

UTC = timezone.utc

@dataclass(frozen=True)
class Exchange:
    code: str
    calendar: str
    symbol: str
    label: str

# Locally traded ETF proxies, not exchange-wide aggregate volume.
ROUTE = (
    Exchange('ASX', 'ASX', 'STW.AX', 'Sydney'),
    Exchange('JPX', 'JPX', '1306.T', 'Tokyo'),
    Exchange('HKEX', 'HKEX', '2800.HK', 'Hong Kong'),
    Exchange('LSE', 'LSE', 'ISF.L', 'London'),
    Exchange('NYSE', 'NYSE', 'SPY', 'New York'),
)

@lru_cache(maxsize=40)
def schedule(name, day):
    cal = mcal.get_calendar(name)
    start = day - timedelta(days=5)
    return cal.schedule(start_date=start, end_date=day+timedelta(days=10))

def session(exchange, now):
    """Return the regular session covering now, including its lunch break."""
    for date, row in schedule(exchange.calendar, now.date()).iterrows():
        if row.market_open <= now < row.market_close:
            return date, row
    return None

class FollowSun:
    """Stick to a session until its final close; lunch does not cause a handover."""
    def __init__(self, route=ROUTE):
        self.route = route
        self.index = None

    def select(self, now):
        if now.tzinfo is None:
            raise ValueError('UTC-aware time required')
        if self.index is not None and session(self.route[self.index], now):
            return self.route[self.index]
        start = 0 if self.index is None else (self.index+1) % len(self.route)
        for step in range(len(self.route)):
            i = (start+step) % len(self.route)
            if session(self.route[i], now):
                self.index = i
                return self.route[i]
        return None

    def next_open(self, now):
        opens = [row.market_open for e in self.route for _,row in schedule(e.calendar,now.date()).iterrows() if row.market_open > now]
        return int(min(opens).timestamp()) if opens else 0

def idle(now, status, exchange=None, next_open=0):
    return dict(schema=1, status=status, exchange=exchange.code if exchange else '',
                symbol=exchange.symbol if exchange else '', generated_at=int(now.timestamp()),
                observed_at=0, valid_until=int(now.timestamp())+180,
                next_open=next_open, change_pct=0., relative_volume=0., turbulence=0.)

def readings(exchange, now, bars, previous_close=None):
    """Use completed 5-minute bars; volume baseline is the same local clock slot.

    Turbulence is one-hour log-return dispersion relative to the median historic
    one-hour dispersion. No overnight return is mixed into intraday volatility.
    """
    active = session(exchange, now)
    if active is None:
        return idle(now,'closed',exchange)
    date, window = active
    if 'break_start' in window and pd.notna(window.break_start) and window.break_start <= now < window.break_end:
        return idle(now,'break',exchange)
    if bars.empty or bars.index.tz is None:
        return idle(now,'unavailable',exchange)
    bars = bars.copy().sort_index()
    bars = bars[~bars.index.duplicated(keep='last')]
    bars.index = bars.index.tz_convert('UTC')
    # Never include a bar until its five-minute interval has finished.
    bars = bars[bars.index + pd.Timedelta(minutes=5) <= pd.Timestamp(now)]
    bars = bars[(bars.Close > 0) & (bars.Volume >= 0)]
    today = bars[(bars.index >= window.market_open) & (bars.index < window.market_close)]
    if 'break_start' in window and pd.notna(window.break_start):
        today = today[~((today.index >= window.break_start) & (today.index < window.break_end))]
    if today.empty:
        return idle(now,'warming',exchange)
    observed = today.index[-1] + pd.Timedelta(minutes=5)
    if (pd.Timestamp(now)-observed).total_seconds() > 1800:
        return idle(now,'stale',exchange)
    cal = mcal.get_calendar(exchange.calendar)
    if previous_close is None or not math.isfinite(previous_close) or previous_close <= 0:
        return idle(now,'warming',exchange)
    local = bars.index.tz_convert(cal.tz)
    slot = today.index[-1].tz_convert(cal.tz).strftime('%H:%M')
    candidates = bars[(local.strftime('%H:%M') == slot) & (bars.index < window.market_open)]
    samples = candidates.Volume.tail(20)
    if len(samples) < 5 or median(samples) <= 0:
        return idle(now,'warming',exchange)
    closes = today.Close.tail(13)
    if len(closes) < 4:
        return idle(now,'warming',exchange)
    returns = [math.log(b/a) for a,b in zip(closes.iloc[:-1],closes.iloc[1:])]
    average = sum(returns)/len(returns)
    volatility = math.sqrt(sum((r-average)**2 for r in returns)/len(returns))
    historical = bars[bars.index < window.market_open]
    windows = []
    for _, day in historical.groupby(historical.index.tz_convert(cal.tz).date):
        log_returns = day.Close.apply(math.log).diff()
        windows.extend(log_returns.rolling(12).std(ddof=0).dropna().tolist())
    if not windows or median(windows) <= 0:
        return idle(now,'warming',exchange)
    normal_volatility = median(windows)
    change = (float(today.Close.iloc[-1])/previous_close-1)*100
    volume = float(today.Volume.iloc[-1])/float(median(samples))
    if not all(math.isfinite(x) for x in [change,volume,volatility]):
        return idle(now,'unavailable',exchange)
    return dict(schema=1,status='delayed',exchange=exchange.code,symbol=exchange.symbol,
                generated_at=int(now.timestamp()),observed_at=int(observed.timestamp()),
                valid_until=int(now.timestamp())+180,next_open=0,
                change_pct=round(max(-100,min(100,change)),4),
                relative_volume=round(max(0,min(10,volume)),4),
                turbulence=round(min(1,volatility/(3*normal_volatility)),4))
